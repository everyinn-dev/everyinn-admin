#!/usr/bin/env node
/**
 * Generate an idempotent SQL upsert statement for `staff` (dev / UAT use).
 * Output contains a bcrypt password hash — write to the git-ignored `.backfill/`
 * directory via `--out .backfill/<name>.sql` and NEVER commit generated `.sql` files.
 *
 * Usage:
 *   node scripts/upsert-staff.mjs \
 *     --phone 0909000001 \
 *     --name "Lễ tân Demo" \
 *     --role receptionist \
 *     --password '<password>' \
 *     --out .backfill/upsert-staff.sql
 *
 * You may also pass the password via the `STAFF_PASSWORD` environment variable.
 *
 * Execute strictly against dev / UAT (NEVER production without explicit owner OK):
 *   npx wrangler d1 execute DB --local --file .backfill/upsert-staff.sql
 *   npx wrangler d1 execute DB --env dev --local --file .backfill/upsert-staff.sql
 *   npx wrangler d1 execute DB --env dev --remote --file .backfill/upsert-staff.sql
 */
import bcrypt from "bcryptjs";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const VALID_ROLES = new Set(["receptionist", "manager"]);

export function quoteSql(value) {
  const s = String(value ?? "");
  if (s.includes("\0")) {
    throw new Error("Null bytes are not permitted in SQL string literals.");
  }
  return `'${s.replaceAll("'", "''")}'`;
}

export function buildUpsertStaffSql({
  phone,
  passwordHash,
  fullName,
  role = "receptionist",
  isActive = true,
}) {
  const cleanPhone = String(phone ?? "").trim();
  if (!/^[0-9+]{8,15}$/.test(cleanPhone)) {
    throw new Error(`Invalid phone format: "${cleanPhone}" (expected 8-15 digits / optional + prefix).`);
  }

  const cleanName = String(fullName ?? "").trim();
  if (!cleanName) {
    throw new Error("fullName must not be empty.");
  }

  if (!VALID_ROLES.has(role)) {
    throw new Error(`Invalid role "${role}". Expected one of: ${[...VALID_ROLES].join(", ")}.`);
  }

  const cleanHash = String(passwordHash ?? "").trim();
  if (!cleanHash.startsWith("$2")) {
    throw new Error("passwordHash must be a valid bcrypt hash.");
  }

  const activeInt = isActive ? 1 : 0;

  return [
    "-- Generated by scripts/upsert-staff.mjs (keep out of git; dev/UAT only)",
    "INSERT INTO staff (phone, password_hash, full_name, role, is_active, updated_at)",
    `VALUES (${quoteSql(cleanPhone)}, ${quoteSql(cleanHash)}, ${quoteSql(cleanName)}, ${quoteSql(role)}, ${activeInt}, datetime('now'))`,
    "ON CONFLICT(phone) DO UPDATE SET",
    "  password_hash = excluded.password_hash,",
    "  full_name = excluded.full_name,",
    "  role = excluded.role,",
    "  is_active = excluded.is_active,",
    "  updated_at = datetime('now');",
    "",
  ].join("\n");
}

export function parseArgs(argv) {
  const out = {
    phone: "",
    name: "",
    role: "receptionist",
    password: process.env.STAFF_PASSWORD ?? "",
    isActive: true,
    outPath: "",
  };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--inactive") {
      out.isActive = false;
      continue;
    }
    const next = argv[i + 1];
    if (arg === "--phone" && next !== undefined) {
      out.phone = next;
      i++;
    } else if (arg === "--name" && next !== undefined) {
      out.name = next;
      i++;
    } else if (arg === "--role" && next !== undefined) {
      out.role = next;
      i++;
    } else if (arg === "--password" && next !== undefined) {
      out.password = next;
      i++;
    } else if (arg === "--out" && next !== undefined) {
      out.outPath = next;
      i++;
    } else {
      throw new Error(`Unknown or incomplete argument: ${arg}`);
    }
  }

  return out;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.phone || !args.name || !args.password) {
    console.error(
      "Usage: node scripts/upsert-staff.mjs --phone <phone> --name <fullName> --password <password> [--role receptionist|manager] [--inactive] [--out .backfill/file.sql]"
    );
    process.exit(1);
  }

  const passwordHash = await bcrypt.hash(args.password, 10);
  const sql = buildUpsertStaffSql({
    phone: args.phone,
    passwordHash,
    fullName: args.name,
    role: args.role,
    isActive: args.isActive,
  });

  if (args.outPath) {
    const absPath = resolve(args.outPath);
    mkdirSync(dirname(absPath), { recursive: true });
    writeFileSync(absPath, sql, { encoding: "utf8", mode: 0o600 });
    console.log(`Wrote idempotent staff upsert SQL for ${args.phone.trim()} (${args.role}) to ${args.outPath}`);
  } else {
    process.stdout.write(sql);
  }
}

const isEntrypoint =
  process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;

if (isEntrypoint) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  });
}
